// Build-time only (never imported by card.mjs).
//   node build-fonts.mjs            -> (re)generates fonts.mjs from the WOFF2 files in ./fonts
//   node build-fonts.mjs --download -> first fetches any missing file from the pinned Fontsource CDN URLs
// Chivo and Chivo Mono (Omnibus-Type, Buenos Aires) are SIL OFL 1.1; licence texts live in fonts/OFL-*.txt.
import { readFile, writeFile, access } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const VERSION = '5.3.0'
const cdn = (id, w) => `https://cdn.jsdelivr.net/fontsource/fonts/${id}@${VERSION}/latin-${w}-normal.woff2`
const FONTS = [
  { name: 'CHIVO_700', file: 'chivo-latin-700-normal.woff2', url: cdn('chivo', 700) },
  { name: 'CHIVO_900', file: 'chivo-latin-900-normal.woff2', url: cdn('chivo', 900) },
  { name: 'CHIVO_MONO_500', file: 'chivo-mono-latin-500-normal.woff2', url: cdn('chivo-mono', 500) },
]
const LICENCES = [
  { file: 'OFL-Chivo.txt', url: `https://cdn.jsdelivr.net/npm/@fontsource/chivo@${VERSION}/LICENSE` },
  { file: 'OFL-ChivoMono.txt', url: `https://cdn.jsdelivr.net/npm/@fontsource/chivo-mono@${VERSION}/LICENSE` },
]

const exists = p => access(p).then(() => true, () => false)
if (process.argv.includes('--download')) {
  for (const f of [...FONTS, ...LICENCES]) {
    const dest = path.join(here, 'fonts', f.file)
    if (await exists(dest)) continue
    const res = await fetch(f.url)
    if (!res.ok) throw new Error(`${f.url}: HTTP ${res.status}`)
    await writeFile(dest, Buffer.from(await res.arrayBuffer()))
    console.log('downloaded', f.file)
  }
}

let out = '// GENERATED by build-fonts.mjs from ./fonts/*.woff2. Do not edit by hand.\n' +
  `// Chivo and Chivo Mono © The Chivo Project Authors (github.com/Omnibus-Type/Chivo), SIL Open Font License 1.1.\n` +
  `// Source: Fontsource CDN, @fontsource/chivo@${VERSION} and @fontsource/chivo-mono@${VERSION}, latin subset.\n`
let total = 0
for (const f of FONTS) {
  const buf = await readFile(path.join(here, 'fonts', f.file))
  if (buf.subarray(0, 4).toString('latin1') !== 'wOF2') throw new Error(`${f.file} is not a WOFF2 file`)
  total += buf.length
  out += `export const ${f.name} = '${buf.toString('base64')}'\n`
}
await writeFile(path.join(here, 'fonts.mjs'), out)
console.log(`fonts.mjs written: ${FONTS.length} faces, ${(total / 1024).toFixed(1)} KB of WOFF2 (budget 250 KB)`)
