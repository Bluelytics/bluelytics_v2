#!/usr/bin/env python3
"""Writes lib/push/firebase_options.dart from the two Firebase client config files.

    python3 tool/gen_firebase_options.py

Run it after replacing android/app/google-services.json or ios/Runner/GoogleService-Info.plist
(Firebase console > Project settings > Your apps). These are client identifiers, public by design:
they ship inside every copy of the app. The server-side service account key is a different thing and
must never be in the repository.
"""
import json
import pathlib
import plistlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
ANDROID_PACKAGE = "com.bluelytics.mobileapp"

android = json.loads((ROOT / "android/app/google-services.json").read_text())
info = android["project_info"]
client = next(c for c in android["client"] if c["client_info"]["android_client_info"]["package_name"] == ANDROID_PACKAGE)
ios = plistlib.loads((ROOT / "ios/Runner/GoogleService-Info.plist").read_bytes())


def options(name, fields):
    lines = [f"  static const FirebaseOptions {name} = FirebaseOptions("]
    lines += [f"    {key}: '{value}'," for key, value in fields if value]
    lines.append("  );")
    return "\n".join(lines)


android_options = options("android", [
    ("apiKey", client["api_key"][0]["current_key"]),
    ("appId", client["client_info"]["mobilesdk_app_id"]),
    ("messagingSenderId", info["project_number"]),
    ("projectId", info["project_id"]),
    ("storageBucket", info.get("storage_bucket")),
])
ios_options = options("ios", [
    ("apiKey", ios["API_KEY"]),
    ("appId", ios["GOOGLE_APP_ID"]),
    ("messagingSenderId", ios["GCM_SENDER_ID"]),
    ("projectId", ios["PROJECT_ID"]),
    ("storageBucket", ios.get("STORAGE_BUCKET")),
    ("iosBundleId", ios["BUNDLE_ID"]),
])

(ROOT / "lib/push/firebase_options.dart").write_text(f"""// GENERATED by tool/gen_firebase_options.py from android/app/google-services.json and
// ios/Runner/GoogleService-Info.plist. Do not edit by hand.
//
// Client identifiers of the Firebase project `{info["project_id"]}`: public by design.
import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;
import 'package:flutter/foundation.dart' show TargetPlatform, defaultTargetPlatform;

abstract final class DefaultFirebaseOptions {{
  static FirebaseOptions get currentPlatform => switch (defaultTargetPlatform) {{
    TargetPlatform.android => android,
    TargetPlatform.iOS => ios,
    _ => throw UnsupportedError('Firebase is only configured for Android and iOS.'),
  }};

{android_options}

{ios_options}
}}
""")
print("wrote lib/push/firebase_options.dart")
